# Работа со встроенными функциями
text = "Python is awesome"
 
# Длина строки
print(f"Длина текста: {len(text)}")
 
# Преобразование регистра
print(f"Верхний регистр: {text.upper()}")
print(f"Нижний регистр: {text.lower()}")
 
# Поиск и замена
print(f"Замена слова: {text.replace('awesome', 'cool')}")
 
# Работа с числами
numbers = [10, 20, 30, 40, 50]
print(f"Максимальное число: {max(numbers)}")
print(f"Минимальное число: {min(numbers)}")
print(f"Сумма чисел: {sum(numbers)}")
