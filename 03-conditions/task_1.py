# Задача 1: Выдача водительских прав
age = int(input("Введите возраст: "))
if age >= 18:
    print("Выдаем водительское удостоверение")
else:
    print("Не выдаем удостоверение")
print('--------')
 
# Задача 2: Стоимость билета в парк
age1 = int(input("Введите возраст посетителя: "))
if age1 <= 5:
    print("Посетитель проходит бесплатно")
elif 5 < age1 < 18:
    print("Билет стоит 10 долларов")
elif age1 >= 18:
    print("Билет стоит 20 долларов")
else:
    print("Ввели некорректные данные")
print('--------')
 
# Задача 3: День недели через match case (современный Python)
numday = int(input("Введите число от 1-7: "))
match numday:
    case 1: print("Понедельник")
    case 2: print("Вторник")
    case 3: print("Среда")
    case 4: print("Четверг")
    case 5: print("Пятница")
    case 6: print("Суббота")
    case 7: print("Воскресенье")
    case _: print("Вы ввели неверное число")
